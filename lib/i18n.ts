export const isLangCode = (s: string | null | undefined): s is LangCode =>
  !!s && LANGUAGES.some((l) => l.code === s);

/** "hi-IN" → "hi", "zh-CN" stays "zh-CN"; unknown codes fall back to English. */
export function langFromVoiceCode(voice: string | null | undefined): LangCode {
  if (isLangCode(voice)) return voice;
  const base = (voice || "en").split("-")[0].toLowerCase();
  return (LANGUAGES.find((l) => l.code === base)?.code) || "en";
}

