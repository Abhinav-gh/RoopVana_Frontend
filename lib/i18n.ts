// Two layers of translation:
// 1. Fixed text below (STRINGS) for the main homepage headings, written for
//    the 11 Indian languages that voice input supports. These read the same
//    every time and work offline. They should be checked by a native speaker
//    of each language before a wider rollout; edit a line here to correct it.
// 2. Everything else on the page (buttons, dropdowns, the guided tour, and
//    the headings in the other 9 languages) is translated automatically by
//    lib/autoTranslate.ts and cached on the device.
//
// `voice` is the speech-recognition code for the mic buttons (only where
// voice input supports the language); `code` is what the SILAI studio uses to
// translate and read its instructions aloud.

export type LangCode =
  | "en" | "hi" | "bn" | "ta" | "te" | "mr" | "gu" | "kn" | "ml" | "pa" | "ur" | "as" | "or"
  | "es" | "fr" | "pt" | "ar" | "sw" | "id" | "zh-CN";

